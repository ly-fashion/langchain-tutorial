@tool
def get_weather(city: str) -> str:
    """查询指定城市的天气信息

    Args:
        city: 城市名称，如 "北京"、"上海"

    Returns:
        天气信息字符串
    """
    if city in WEATHER_DATA:
        w = WEATHER_DATA[city]
        return (
            f"📍 {city}天气：\n"
            f"  天气：{w['天气']}\n"
            f"  温度：{w['温度']}\n"
            f"  湿度：{w['湿度']}\n"
            f"  风力：{w['风力']}\n"
            f"  💡 建议：{w['建议']}"
        )
    return f"暂无{city}的天气数据，支持的城市：{', '.join(WEATHER_DATA.keys())}"


@tool
def get_weather_forecast(city: str, days: int = 3) -> str:
    """查询城市未来几天天气预报

    Args:
        city: 城市名称
        days: 预报天数（1-7）

    Returns:
        天气预报字符串
    """
    if city not in WEATHER_DATA:
        return f"暂无{city}的天气数据"

    base = WEATHER_DATA[city]
    forecast = [f"📍 {city}未来{days}天天气预报：\n"]

    # 模拟预报数据
    import random
    weather_types = ["晴", "多云", "阴", "小雨", "阵雨"]

    for i in range(min(days, 7)):
        day_weather = random.choice(weather_types) if i > 0 else base["天气"]
        temp_high = int(base["温度"].replace("°C", "")) + random.randint(-3, 3)
        temp_low = temp_high - random.randint(5, 10)
        forecast.append(f"  第{i+1}天：{day_weather} {temp_low}°C ~ {temp_high}°C")

    return "\n".join(forecast)
