@tool
def search_travel_knowledge(query: str) -> str:
    """搜索旅游相关知识，包括签证、行李、交通、住宿、美食、安全等信息

    Args:
        query: 查询关键词，如 "签证"、"行李"、"美食"、"安全"

    Returns:
        相关知识信息
    """
    query_lower = query.lower()
    results = []

    for category, items in KNOWLEDGE_BASE.items():
        if category in query_lower:
            result = f"📚 【{category}】相关知识：\n\n"
            for key, value in items.items():
                result += f"  {key}：{value}\n\n"
            results.append(result)

    if results:
        return "\n".join(results)

    # 模糊搜索
    for category, items in KNOWLEDGE_BASE.items():
        for key, value in items.items():
            if query_lower in key.lower() or query_lower in value.lower():
                results.append(f"📚 找到相关信息：\n  {key}：{value}")

    if results:
        return "\n\n".join(results)

    return f"未找到「{query}」的相关知识，您可以询问：签证、行李、交通、住宿、美食、安全、摄影、购物等话题"
